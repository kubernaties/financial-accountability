const {getAuto,setAuto,themeAt,wantedTheme,applyAuto}=await import("../js/ui/theme-auto.js");
let bad=0;const t=(n,c)=>{if(!c){bad++;console.log("FAIL",n);}else console.log("PASS",n);};
